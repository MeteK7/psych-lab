import { Component, afterNextRender, signal } from '@angular/core';

import { ASSETS, assetText } from '../../shared/visual/assets/catalogue';
import { AssetEntry, FileFacts, assetProblems, assetVisualId } from '../../shared/visual/assets/manifest';

interface Row {
  entry: AssetEntry;
  alt: string;
  origin: string;
  recorded: string;
}

function originWords(entry: AssetEntry): string {
  const o = entry.origin;
  if (o.kind === 'exported') return `Exported from ${o.composition}@${o.version}, theme ${o.theme}@${o.themeVersion}${o.seed ? `, seed ${o.seed}` : ''}`;
  if (o.kind === 'authored') return `Made by hand: ${o.author}`;
  const brief = Object.entries(o.brief)
    .map(([k, v]) => `${k} ${v}`)
    .join(', ');
  return `Generated by ${o.provider} (brief: ${brief}${o.seed ? `; seed ${o.seed}` : ''})`;
}

/** A file's size and SHA-256 checksum as the browser fetches it; null when it can't. */
async function fetched(path: string): Promise<FileFacts | null> {
  try {
    const response = await fetch(path, { cache: 'no-store' });
    if (!response.ok) return null;
    const data = new Uint8Array(await response.arrayBuffer());
    const digest = new Uint8Array(await crypto.subtle.digest('SHA-256', data));
    return { bytes: data.length, sha256: [...digest].map((b) => b.toString(16).padStart(2, '0')).join('') };
  } catch {
    return null;
  }
}

/**
 * The Visual Lab's assets section (milestone M7, S8): every asset in the manifest, in both schemes,
 * with its text alternative, where it came from, its licence and its review status, and a live
 * check that the files served are the files the manifest describes. Drafts show here only.
 */
@Component({
  selector: 'app-lab-assets',
  styleUrls: ['./lab.css'],
  styles: `
    dl { display: grid; grid-template-columns: max-content 1fr; gap: 0.2rem 1rem; font-size: 0.9rem; margin: 0.5rem 0; }
    dt { color: var(--muted); }
    dd { margin: 0; overflow-wrap: anywhere; }
    img { display: block; max-width: 100%; height: auto; }
    .status { font-weight: 400; font-size: 0.9rem; color: var(--muted); }
  `,
  template: `
    <section class="scene" aria-labelledby="lab-assets">
      <h2 id="lab-assets">Assets<span class="meta"> · S8 · M7 · the manifest</span></h2>
      <p class="note muted">
        Pictures that are files, not drawn live. Each has one entry in the manifest: its files for light and dark with their size and
        checksum, its text alternative, where it came from, its licence, and whether it has been reviewed. Only approved assets reach
        a person; drafts show here alone. A changed file is a new version.
      </p>
      @for (row of rows; track row.entry.id) {
        <h3>{{ row.entry.id }}&#64;{{ row.entry.version }} <span class="status" [attr.data-asset-status]="row.entry.id">· {{ row.entry.status }}</span></h3>
        <div class="grid">
          @for (scheme of schemes; track scheme) {
            <div class="panel" [class]="scheme">
              <span class="tag">{{ row.entry.files[scheme].path }} · {{ scheme }}</span>
              <img [src]="row.entry.files[scheme].path" [alt]="row.alt" [width]="row.entry.width" [height]="row.entry.height"
                   [attr.data-asset]="row.entry.id + '-' + scheme" />
            </div>
          }
        </div>
        <dl [attr.data-asset-facts]="row.entry.id">
          <dt>Text alternative</dt><dd>{{ row.alt }}</dd>
          <dt>Where it came from</dt><dd>{{ row.origin }}</dd>
          <dt>Licence</dt><dd>{{ row.entry.licence }}</dd>
          <dt>Review</dt>
          <dd>
            @if (row.entry.review; as r) { Approved by {{ r.by }} on {{ r.on }} } @else { Not reviewed yet }
          </dd>
          <dt>Reaches a person</dt>
          <dd>{{ row.entry.status === 'approved' ? 'Yes, recorded as ' + row.recorded : 'No: a draft is shown in the Lab only' }}</dd>
          <dt>Files</dt>
          <dd [attr.data-asset-check]="row.entry.id">
            @if (checks()[row.entry.id]; as problems) {
              @if (problems.length) {
                <ul class="problems" [attr.aria-label]="'Asset problems: ' + row.entry.id">@for (p of problems; track p) { <li>{{ p }}</li> }</ul>
              } @else {
                The files served match the manifest (size and SHA-256): {{ row.entry.files.light.sha256.slice(0, 12) }}… and {{ row.entry.files.dark.sha256.slice(0, 12) }}…
              }
            } @else { Checking… }
          </dd>
        </dl>
      } @empty {
        <p>No assets yet.</p>
      }
    </section>
  `,
})
export class LabAssets {
  protected readonly schemes = ['light', 'dark'] as const;
  protected readonly rows: Row[] = ASSETS.map((entry) => ({ entry, alt: assetText(entry.alt) ?? '', origin: originWords(entry), recorded: assetVisualId(entry) }));
  /** Each asset's problems against the files as served; absent while checking. */
  protected readonly checks = signal<Record<string, string[]>>({});

  constructor() {
    afterNextRender(async () => {
      for (const entry of ASSETS) {
        const facts = new Map<string, FileFacts | null>();
        for (const path of new Set([entry.files.light.path, entry.files.dark.path])) facts.set(path, await fetched(path));
        const problems = assetProblems(entry, (path) => facts.get(path) ?? null, assetText);
        this.checks.update((c) => ({ ...c, [entry.id]: problems }));
      }
    });
  }
}
